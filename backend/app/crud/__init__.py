# 本包集中放置按业务实体划分的 CRUD 类（project / user / review 等），
# 由 service 层调用，路由层不直接访问数据库。
#
# 设计约定：
#   - 每个 CRUD 类只做「单实体读写 + 权限条件拼接」，不实现业务状态机；
#   - 事务边界由 service 层控制，本包方法只 flush 不 commit；
#   - 所有查询默认过滤软删除（is_deleted=0）。
#
# 本文件不导出具体类，使用方按模块显式导入，避免循环依赖。
