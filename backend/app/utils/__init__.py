# 工具类包初始化
#
# 本包放置与具体业务实体无关、可被多层复用的通用工具：
#   - excel_helper：Excel 导入解析、模板生成与导出；
#   - redis_cache：Redis 缓存单例、缓存装饰器与 Token 黑名单。
#
# 设计约定：
#   - 工具函数不依赖 CRUD/service，避免反向依赖；
#   - 外部依赖（openpyxl、redis）均为可选导入，缺失时降级而不是让应用启动失败；
#   - 本文件不做聚合导出，使用方按模块显式导入，保持依赖清晰。
